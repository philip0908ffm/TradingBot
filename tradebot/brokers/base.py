"""Broker abstraction.

Every concrete broker (Binance, Alpaca, Yahoo data-only, Paper) implements ``Broker``.
The rest of the application ONLY talks to this interface.

Methods are synchronous; the trading engine calls them through ``asyncio.to_thread``.
Implementations raise ``BrokerError`` (or a subclass) for any failure the user should see.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime

import pandas as pd

from tradebot.core.models import AssetClass, Order, OrderType, Side


class BrokerError(Exception):
    """Any broker-related failure (network, auth, rejected order...)."""


class AuthenticationError(BrokerError):
    pass


class NotSupportedError(BrokerError):
    pass


class InsufficientFundsError(BrokerError):
    """Not enough cash / holdings for an order."""


class InvalidOrderError(BrokerError):
    """Order rejected for formal reasons (size, price, precision, minimum notional...)."""


class BadSymbolError(BrokerError):
    """Unknown or unsupported symbol."""


class NetworkError(BrokerError):
    """Connection problems, timeouts, exchange unavailable."""


class RateLimitError(NetworkError):
    """Too many requests; retry later."""


@dataclass
class CredentialField:
    """Describes one credential input for the Settings page."""

    key: str  # e.g. "api_key"
    label: str  # e.g. "API Key"
    secret: bool = True  # render as password field


@dataclass
class BrokerInfo:
    key: str  # registry key, e.g. "binance"
    name: str  # display name
    asset_classes: list[AssetClass]
    supports_trading: bool  # False for data-only providers (yahoo)
    requires_credentials_for_data: bool  # can we fetch prices without keys?
    credential_fields: list[CredentialField] = field(default_factory=list)
    has_sandbox: bool = False  # offers a testnet / paper environment on the broker side
    quote_currency: str = "USDT"  # default cash currency
    description: str = ""


class Broker(ABC):
    """Abstract broker. ``credentials`` keys correspond to ``info().credential_fields``.

    ``options`` may contain broker-specific non-secret settings, e.g. ``{"sandbox": True}``.
    """

    def __init__(self, credentials: dict | None = None, options: dict | None = None) -> None:
        self.credentials = credentials or {}
        self.options = options or {}

    # ---- metadata -------------------------------------------------------------------
    @classmethod
    @abstractmethod
    def info(cls) -> BrokerInfo: ...

    # ---- market data (must work without credentials if requires_credentials_for_data is False)
    @abstractmethod
    def fetch_ohlcv(
        self,
        symbol: str,
        timeframe: str,
        start: datetime | None = None,
        end: datetime | None = None,
        limit: int | None = None,
    ) -> pd.DataFrame:
        """Return candles as DataFrame (UTC DatetimeIndex; columns open, high, low, close, volume).

        - ``start``/``end`` inclusive range; pagination handled internally.
        - If only ``limit`` is given: the most recent ``limit`` candles.
        - Implementations should only return CLOSED candles where feasible is NOT required;
          the engine drops the last (possibly still forming) candle itself.
        """

    @abstractmethod
    def fetch_price(self, symbol: str) -> float:
        """Latest traded price."""

    @abstractmethod
    def list_symbols(self) -> list[str]:
        """Tradable/known symbols (may be a curated list for data providers)."""

    # ---- account (requires credentials) ---------------------------------------------
    def test_connection(self) -> str:
        """Verify credentials; return a human-readable success message or raise BrokerError."""
        self.fetch_balance()
        return "Verbindung erfolgreich"

    @abstractmethod
    def fetch_balance(self) -> dict[str, float]:
        """Free balances per currency/asset, e.g. {"USDT": 1000.0, "BTC": 0.01}."""

    @abstractmethod
    def place_order(
        self,
        symbol: str,
        side: Side,
        quantity: float,
        order_type: OrderType = OrderType.MARKET,
        price: float | None = None,
    ) -> Order:
        """Submit an order. Returns the resulting Order (status, avg fill price, fee).

        Implementations SHOULD also accept an optional keyword ``client_order_id: str``
        (unique id generated by the engine, sent to the exchange so a lost response can be
        looked up later via ``fetch_order_by_client_id``). The engine only passes it to
        brokers whose ``place_order`` signature has that parameter.
        If (part of) the fee was charged in the BASE asset, set ``order.raw["fee_base"]``
        (quantity of the base asset withheld) – see ``order_fee_base``.
        """

    @abstractmethod
    def cancel_order(self, order_id: str, symbol: str) -> None: ...

    def fetch_order(self, order_id: str, symbol: str) -> Order:
        """Current state of an order (status, filled qty, avg price, fee). Default: unsupported."""
        raise NotSupportedError(
            f"{self.info().name}: Abfrage des Orderstatus wird nicht unterstützt."
        )

    def fetch_order_by_client_id(self, client_order_id: str, symbol: str) -> Order | None:
        """Look up an order by the client order id given to ``place_order``.

        Returns the Order, ``None`` if the broker definitely has no such order, raises
        ``NotSupportedError`` if lookups are not possible, other ``BrokerError`` if the
        state cannot be determined right now. Default: unsupported.
        """
        raise NotSupportedError(
            f"{self.info().name}: Suche nach Client-Order-ID wird nicht unterstützt."
        )

    def normalize_quantity(self, symbol: str, quantity: float) -> float:
        """Round quantity to the broker's lot-size rules. Default: unchanged."""
        return quantity

    def min_order_value(self, symbol: str) -> float:
        """Minimum notional in quote currency. Default 0."""
        return 0.0


def order_fee_base(order: Order) -> float:
    """Quantity of the base asset withheld as fee (``order.raw["fee_base"]``), else 0."""
    raw = order.raw if isinstance(order.raw, dict) else {}
    try:
        return max(float(raw.get("fee_base") or 0.0), 0.0)
    except (TypeError, ValueError):
        return 0.0


def supports_client_order_id(broker: "Broker") -> bool:
    """Whether ``broker.place_order`` accepts the ``client_order_id`` keyword."""
    import inspect

    try:
        params = inspect.signature(broker.place_order).parameters
    except (TypeError, ValueError):
        return False
    return "client_order_id" in params
